export function getGameBySlug(slug: string): Game | undefined {
  return games.find((g) => g.slug === slug);
}

/** مسیر کامل صفحه اختصاصی بازی */
export function gamePath(game: Game): string {
  return `/games/${game.slug}`;
}

// اسکیمای VideoGame برای صفحه اختصاصی هر بازی — بدون invent کردن رتبه/قیمت
export function gameSchemaJson(game: Game): string {
  return JSON.stringify({
    "@context": "https://schema.org",
    "@type": "VideoGame",
    name: game.title,
    url: game.url,
    description: game.tagline,
    genre: game.badge.replace("بازی ", ""),
    gamePlatform: ["Android"],
    platform: ["Android"],
    operatingSystem: "Android",
    applicationCategory: "GameApplication",
    inLanguage: "fa",
    publisher: {
      "@type": "Organization",
      name: siteConfig.name,
      url: siteConfig.url,
    },
  });
}

// اسکیمای ItemList برای سکشن بازی‌ها و صفحه /games — بدون invent قیمت
export function gamesListSchemaJson(): string {
  return JSON.stringify({
    "@context": "https://schema.org",
    "@type": "ItemList",
    name: "بازی‌های موبایل JSDevelop",
    itemListElement: games.map((game, index) => ({
      "@type": "ListItem",
      position: index + 1,
      item: {
        "@type": "VideoGame",
        name: game.title,
        url: game.url,
        description: game.tagline,
        genre: game.badge.replace("بازی ", ""),
        gamePlatform: ["Android"],
        operatingSystem: "Android",
        applicationCategory: "GameApplication",
        publisher: {
          "@type": "Organization",
          name: siteConfig.name,
          url: siteConfig.url,
        },
      },
    })),
  });
}

// اسکیمای BreadcrumbList — مسیر: خانه ← بازی‌ها ← بازی
export function gameBreadcrumbSchemaJson(game: Game): string {
  return JSON.stringify({
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [
      { "@type": "ListItem", position: 1, name: "صفحه اصلی", item: siteConfig.url },
      { "@type": "ListItem", position: 2, name: "بازی‌ها", item: `${siteConfig.url}/games` },
      { "@type": "ListItem", position: 3, name: game.title, item: `${siteConfig.url}${gamePath(game)}` },
    ],
  });
}

// اسکیمای FAQPage محتوای صفحه اختصاصی هر بازی — مطابق خط‌مشی گوگل متن کامل تکرار می‌شود
export function gameFaqSchemaJson(game: Game): string {
  return JSON.stringify({
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: game.faqs.map((faq) => ({
      "@type": "Question",
      name: faq.question,
      acceptedAnswer: { "@type": "Answer", text: faq.answer },
    })),
  });
}
