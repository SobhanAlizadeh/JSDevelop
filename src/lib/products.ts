export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

/** مسیر کامل صفحه اختصاصی محصول */
export function productPath(product: Product): string {
  return `/products/${product.slug}`;
}

// اسکیمای SoftwareApplication برای صفحه اختصاصی هر محصول — بدون invent قیمت
export function productSchemaJson(product: Product): string {
  return JSON.stringify({
    "@context": "https://schema.org",
    "@type": "SoftwareApplication",
    name: product.title,
    url: product.url,
    description: product.description,
    applicationCategory:
      product.slug === "school-management"
        ? "EducationalApplication"
        : "BusinessApplication",
    operatingSystem: "Web",
    publisher: {
      "@type": "Organization",
      name: siteConfig.name,
      url: siteConfig.url,
    },
  });
}

// اسکیمای BreadcrumbList — مسیر: خانه ← محصولات ← محصول
export function breadcrumbSchemaJson(product: Product): string {
  return JSON.stringify({
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [
      { "@type": "ListItem", position: 1, name: "صفحه اصلی", item: siteConfig.url },
      { "@type": "ListItem", position: 2, name: "محصولات", item: `${siteConfig.url}/#products` },
      { "@type": "ListItem", position: 3, name: product.title, item: `${siteConfig.url}${productPath(product)}` },
    ],
  });
}

// اسکیمای FAQPage محتوای صفحه اختصاصی — مطابق خط‌مشی گوگل متن کامل تکرار می‌شود
export function faqSchemaJson(product: Product): string {
  return JSON.stringify({
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: product.faqs.map((faq) => ({
      "@type": "Question",
      name: faq.question,
      acceptedAnswer: { "@type": "Answer", text: faq.answer },
    })),
  });
}
